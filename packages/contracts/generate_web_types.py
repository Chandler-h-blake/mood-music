"""Generate Web response types from the local API's OpenAPI schema (no server needed)."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "services/api/src"))

from moodmusic_api.main import create_app


def typescript(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1].replace("-", "_")
    if "anyOf" in schema:
        return " | ".join(typescript(item) for item in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(
            json.dumps(item, ensure_ascii=False) for item in schema["enum"]
        )
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema['items'])}>"
    if kind == "object":
        if "properties" not in schema:
            additional = schema.get("additionalProperties")
            return f"Record<string, {typescript(additional) if isinstance(additional, dict) else 'unknown'}>"
        # Responses serialize defaults too. Inputs remain validated by the API.
        return (
            "{\n"
            + "\n".join(
                f"  {json.dumps(name)}{'?' if typescript(value) == 'unknown' else ''}: "
                f"{typescript(value)};"
                for name, value in schema["properties"].items()
            )
            + "\n}"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def validator(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1].replace("-", "_") + "Schema"
    if "anyOf" in schema:
        return (
            "z.union([" + ", ".join(validator(item) for item in schema["anyOf"]) + "])"
        )
    if "enum" in schema:
        return "z.enum(" + json.dumps(schema["enum"], ensure_ascii=False) + ")"
    if "const" in schema:
        return "z.literal(" + json.dumps(schema["const"]) + ")"
    kind = schema.get("type")
    if kind == "array":
        return "z.array(" + validator(schema["items"]) + ")"
    if kind == "object":
        if "properties" not in schema:
            return "z.record(z.unknown())"
        return (
            "z.object({\n"
            + "\n".join(
                f"  {json.dumps(name)}: {validator(value)},"
                for name, value in schema["properties"].items()
            )
            + "\n})"
        )
    result = {
        "string": "z.string()",
        "integer": "z.number().int()",
        "number": "z.number()",
        "boolean": "z.boolean()",
        "null": "z.null()",
    }.get(kind, "z.unknown()")
    for constraint, method in (
        ("minimum", "min"),
        ("maximum", "max"),
        ("minLength", "min"),
        ("maxLength", "max"),
    ):
        if constraint in schema:
            result += f".{method}({schema[constraint]})"
    return result


def main() -> None:
    schemas = create_app().openapi()["components"]["schemas"]
    output = (
        "// Generated by packages/contracts/generate_web_types.py. Do not edit.\n\n"
    )
    output += (
        "\n\n".join(
            f"export type {name.replace('-', '_')} = {typescript(schema)};"
            for name, schema in sorted(schemas.items())
        )
        + "\n"
    )
    (ROOT / "apps/web/lib/api-types.ts").write_text(output, encoding="utf-8")
    validators = (
        "// Generated by packages/contracts/generate_web_types.py. Do not edit.\n"
        'import { z } from "zod";\nimport type * as Api from "./api-types";\n\n'
    )
    validators += (
        "\n\n".join(
            f"export const {name.replace('-', '_')}Schema: z.ZodType<Api.{name.replace('-', '_')}>"
            f" = z.lazy(() => {validator(schema)});"
            for name, schema in sorted(schemas.items())
        )
        + "\n"
    )
    (ROOT / "apps/web/lib/api-schemas.ts").write_text(validators, encoding="utf-8")


if __name__ == "__main__":
    main()
